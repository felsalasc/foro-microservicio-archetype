-- Ejecutar una sola vez en el esquema PROPIO del servicio generado.
-- No crea usuarios ni modifica tablas de los otros microservicios.
CREATE TABLE RECURSOS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT CK_RECURSOS_ID CHECK (ID > 0),
    CONSTRAINT CK_RECURSOS_NOMBRE CHECK (LENGTH(TRIM(NOMBRE)) BETWEEN 2 AND 100)
);
